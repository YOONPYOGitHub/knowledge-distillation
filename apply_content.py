hits = set()
def rep(tf, mp, sidx):
    for p in tf.paragraphs:
        txt = "".join(r.text for r in p.runs).strip()
        if txt in mp and p.runs:
            p.runs[0].text = mp[txt]
            for r in p.runs[1:]:
                r.text = ""
            hits.add((sidx, txt))

for idx, s in enumerate(prs.slides):
    mp = M.get(idx, {})
    for sh in s.shapes:
        if sh.has_text_frame:
            rep(sh.text_frame, mp, idx)
        if sh.has_table:
            for row in sh.table.rows:
                for c in row.cells:
                    rep(c.text_frame, mp, idx)

prs.save(OUT)
print(f"saved -> {OUT}")
